
import traceback

from fastapi import APIRouter, HTTPException
from pydantic import BaseModel, Field, field_validator

from app.services.price_model import predict_property_price

router = APIRouter(
    prefix="/api/price-prediction",
    tags=["Price Prediction"],
)


class PropertyDetails(BaseModel):
    property_type: str = Field(...)
    listing_type: str = Field(...)
    area_sqft: float = Field(..., gt=0)
    bedrooms: int = Field(default=0, ge=0)
    bathrooms: int = Field(default=0, ge=0)
    city: str = Field(..., min_length=1)
    locality: str = ""

    @field_validator("property_type")
    @classmethod
    def validate_property_type(cls, value: str) -> str:
        value = value.strip().lower()
        if value not in {"apartment", "villa", "plot", "commercial"}:
            raise ValueError(
                "property_type must be apartment, villa, plot, or commercial"
            )
        return value

    @field_validator("listing_type")
    @classmethod
    def validate_listing_type(cls, value: str) -> str:
        value = value.strip().lower()
        if value not in {"sale", "rent"}:
            raise ValueError("listing_type must be sale or rent")
        return value

    @field_validator("city")
    @classmethod
    def clean_city(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("city cannot be empty")
        return value

    @field_validator("locality")
    @classmethod
    def clean_locality(cls, value: str) -> str:
        return value.strip()


@router.post("/")
def predict_price(property_data: PropertyDetails):
    try:
        price = predict_property_price(property_data.model_dump())

        return {
            "success": True,
            "message": "Prediction generated by trained model.",
            "predicted_price": price,
            "currency": "INR",
            "data_quality": "synthetic_demo",
        }

    except FileNotFoundError as exc:
        print(f"MODEL FILE ERROR: {exc}")
        raise HTTPException(status_code=503, detail=str(exc))

    except Exception as exc:
        print("\n========== PRICE PREDICTION ERROR ==========")
        traceback.print_exc()
        print("============================================\n")

        raise HTTPException(
            status_code=500,
            detail=f"Prediction failed: {type(exc).__name__}: {exc}",
        )
